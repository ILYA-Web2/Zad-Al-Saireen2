  static HadithModel getForDay(DateTime date) {
    final index = (date.year * 366 + date.dayOfYear) % all.length;
    return all[index.abs()];
  }

  static List<HadithModel> getByCategory(String category) {
    if (category == 'الكل') return all;
    return all.where((h) => h.category == category).toList();
  }

  static List<String> get categories {
    final cats = all.map((h) => h.category).toSet().toList();
    cats.sort();
    return ['الكل', ...cats];
  }
